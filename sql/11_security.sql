USE ROLE ACCOUNTADMIN;
SET my_user = CURRENT_USER();
SET my_wh   = CURRENT_WAREHOUSE();

-- 9-1. 역할과 권한
CREATE ROLE IF NOT EXISTS AE101_ANALYST_SEOUL;
CREATE ROLE IF NOT EXISTS AE101_MANAGER;
GRANT ROLE AE101_ANALYST_SEOUL TO ROLE SYSADMIN;
GRANT ROLE AE101_MANAGER       TO ROLE SYSADMIN;
GRANT ROLE AE101_ANALYST_SEOUL TO USER IDENTIFIER($my_user);   -- 실습용: 본인에게 두 역할을 부여
GRANT ROLE AE101_MANAGER       TO USER IDENTIFIER($my_user);

GRANT USAGE ON WAREHOUSE IDENTIFIER($my_wh)              TO ROLE AE101_ANALYST_SEOUL;
GRANT USAGE ON WAREHOUSE IDENTIFIER($my_wh)              TO ROLE AE101_MANAGER;
GRANT USAGE ON DATABASE AE101_SALES_ENT                  TO ROLE AE101_ANALYST_SEOUL;
GRANT USAGE ON DATABASE AE101_SALES_ENT                  TO ROLE AE101_MANAGER;
GRANT USAGE ON SCHEMA AE101_SALES_ENT.MART               TO ROLE AE101_ANALYST_SEOUL;
GRANT USAGE ON SCHEMA AE101_SALES_ENT.MART               TO ROLE AE101_MANAGER;
GRANT SELECT ON ALL VIEWS IN SCHEMA AE101_SALES_ENT.MART TO ROLE AE101_ANALYST_SEOUL;   -- Fact 테이블 권한은 주지 않음
GRANT SELECT ON ALL VIEWS IN SCHEMA AE101_SALES_ENT.MART TO ROLE AE101_MANAGER;
-- STEP 8 은 뷰를 CREATE OR REPLACE 로 다시 만들어 기존 권한이 사라집니다. 앞으로 만들 뷰에도 같은 권한을 줍니다.
GRANT SELECT ON FUTURE VIEWS IN SCHEMA AE101_SALES_ENT.MART TO ROLE AE101_ANALYST_SEOUL;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA AE101_SALES_ENT.MART TO ROLE AE101_MANAGER;
GRANT SELECT ON TABLE AE101_SALES_ENT.MART.DIM_CUSTOMER  TO ROLE AE101_ANALYST_SEOUL;
GRANT SELECT ON TABLE AE101_SALES_ENT.MART.DIM_CUSTOMER  TO ROLE AE101_MANAGER;
GRANT SELECT ON TABLE AE101_SALES_ENT.MART.DIM_PRODUCT   TO ROLE AE101_ANALYST_SEOUL;
GRANT SELECT ON TABLE AE101_SALES_ENT.MART.DIM_PRODUCT   TO ROLE AE101_MANAGER;
GRANT SELECT ON TABLE AE101_SALES_ENT.MART.DIM_DATE      TO ROLE AE101_ANALYST_SEOUL;
GRANT SELECT ON TABLE AE101_SALES_ENT.MART.DIM_DATE      TO ROLE AE101_MANAGER;

-- 9-2. 역할-지역 매핑 ('*' = 전체 지역)
CREATE TABLE IF NOT EXISTS SECURITY.REGION_ACCESS_MAP (role_name VARCHAR, allowed_region VARCHAR);
DELETE FROM SECURITY.REGION_ACCESS_MAP;
INSERT INTO SECURITY.REGION_ACCESS_MAP (role_name, allowed_region) VALUES
  ('AE101_ANALYST_SEOUL', '서울'),
  ('AE101_MANAGER',       '*');

-- 9-2. Row Access Policy (인자 이름을 컬럼명과 다르게 둬야 서브쿼리에서 헷갈리지 않습니다)
CREATE ROW ACCESS POLICY IF NOT EXISTS SECURITY.RAP_CUSTOMER_REGION
  AS (cust_region VARCHAR) RETURNS BOOLEAN -> TRUE;

ALTER ROW ACCESS POLICY SECURITY.RAP_CUSTOMER_REGION SET BODY ->
  CURRENT_ROLE() IN ('ACCOUNTADMIN', 'SYSADMIN')
  OR EXISTS (
    SELECT 1 FROM AE101_SALES_ENT.SECURITY.REGION_ACCESS_MAP m
    WHERE m.role_name = CURRENT_ROLE()
      AND (m.allowed_region = '*' OR m.allowed_region = cust_region));

ALTER TABLE MART.DIM_CUSTOMER DROP ALL ROW ACCESS POLICIES;
ALTER TABLE MART.DIM_CUSTOMER ADD ROW ACCESS POLICY SECURITY.RAP_CUSTOMER_REGION ON (region);

-- 9-3. Masking Policy : 허용 역할만 원문, 나머지는 '****@도메인'
CREATE MASKING POLICY IF NOT EXISTS SECURITY.MASK_EMAIL
  AS (val VARCHAR) RETURNS VARCHAR -> val;

ALTER MASKING POLICY SECURITY.MASK_EMAIL SET BODY ->
  CASE WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN', 'AE101_MANAGER') THEN val
       WHEN val IS NULL THEN NULL
       ELSE REGEXP_REPLACE(val, '^[^@]+', '****') END;

ALTER TABLE MART.DIM_CUSTOMER MODIFY COLUMN email SET MASKING POLICY SECURITY.MASK_EMAIL FORCE;

